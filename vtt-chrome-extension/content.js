  function syncChipUI() {
    if (!state.chipEl) return;
    var btns = state.chipEl.querySelectorAll("[data-lang]");
    btns.forEach(function (b) {
      b.classList.toggle(
        "active",
        state.enabled && b.getAttribute("data-lang") === state.targetLang
      );
    });
    var dot = state.chipEl.querySelector("#vtt-chip-dot");
    if (dot) {
      dot.classList.toggle("vtt-off", !state.enabled);
      dot.classList.toggle("vtt-live", state.isSpeechActive);
    }
  }

  function positionOverlayOverVideo(video) {
    ensureUI();
    if (!video || !state.wrapEl || !state.chipEl) return;
    var rect = video.getBoundingClientRect();

    if (
      rect.width < 120 ||
      rect.height < 80 ||
      rect.bottom < 40 ||
      rect.top > window.innerHeight - 40
    ) {
      state.wrapEl.classList.add("vtt-hidden");
      state.chipEl.classList.add("vtt-chip-hidden");
      return;
    }

    var isFullscreen = Boolean(
      document.fullscreenElement || document.webkitFullscreenElement
    );
    var visibleBottom = Math.min(window.innerHeight, rect.bottom);
    var minTop = isFullscreen ? 10 : 60;
    var visibleTop = Math.max(minTop, rect.top + 8);
    var rightOffset = Math.max(8, window.innerWidth - rect.right + 8);
    var centerX = rect.left + rect.width / 2;
    var bottomOffset = Math.max(
      24,
      window.innerHeight - visibleBottom + Math.min(54, rect.height * 0.11)
    );

    state.wrapEl.style.left = Math.round(centerX) + "px";
    state.wrapEl.style.bottom = Math.round(bottomOffset) + "px";
    state.wrapEl.style.maxWidth =
      Math.round(Math.min(760, rect.width * 0.88)) + "px";

    state.chipEl.style.top = Math.round(visibleTop) + "px";
    state.chipEl.style.right = Math.round(rightOffset) + "px";
    state.chipEl.style.left = "auto";
    state.chipEl.classList.remove("vtt-chip-hidden");
  }

  /**
   * Calculate comfortable reading hold duration based on text length
   * (minimum 2.8 seconds, up to 5.2 seconds for longer sentences).
   */
  function computeReadingHoldMs(text) {
    var len = (text || "").length;
    return Math.max(2800, Math.min(5200, 1900 + len * 52));
  }

  function showSubtitleText(mainText, subText, durationMs) {
    ensureUI();
    if (!state.enabled || !mainText) {
      if (state.wrapEl) state.wrapEl.classList.add("vtt-hidden");
      return;
    }

    if (state.activeVideo) {
      positionOverlayOverVideo(state.activeVideo);
    }

    state.mainLineEl.textContent = mainText;
    state.mainLineEl.dir = isRTL(mainText) ? "rtl" : "ltr";

    if (subText && subText !== mainText) {
      state.subLineEl.textContent = subText;
      state.subLineEl.dir = isRTL(subText) ? "rtl" : "ltr";
      state.subLineEl.style.display = "block";
    } else {
      state.subLineEl.style.display = "none";
    }

    state.wrapEl.classList.remove("vtt-hidden");

    if (state.hideTimer) clearTimeout(state.hideTimer);
    if (durationMs) {
      state.hideTimer = setTimeout(function () {
        if (state.wrapEl) state.wrapEl.classList.add("vtt-hidden");
      }, durationMs);
    }
  }

