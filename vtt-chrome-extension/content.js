  function isRTL(str) {
    return /[\u0600-\u06FF]/.test(str || "");
  }

  function normalizeFa(text) {
    if (!text) return "";
    return String(text)
      .replace(/[\u064A\u0649]/g, "\u06CC")
      .replace(/\u0643/g, "\u06A9")
      .replace(/\s+/g, " ")
      .trim();
  }

  function formatTime(sec, comma) {
    var s = Math.max(0, Number(sec) || 0);
    var hh = Math.floor(s / 3600);
    var mm = Math.floor((s % 3600) / 60);
    var ss = Math.floor(s % 60);
    var ms = Math.round((s - Math.floor(s)) * 1000);
    if (ms === 1000) {
      ms = 0;
      ss += 1;
      if (ss === 60) {
        ss = 0;
        mm += 1;
        if (mm === 60) {
          mm = 0;
          hh += 1;
        }
      }
    }
    var sep = comma ? "," : ".";
    return (
      String(hh).padStart(2, "0") +
      ":" +
      String(mm).padStart(2, "0") +
      ":" +
      String(ss).padStart(2, "0") +
      sep +
      String(ms).padStart(3, "0")
    );
  }

  function exportSubtitles(format) {
    var list =
      state.recordedHistory.length > 0 ? state.recordedHistory : state.cues;
    if (!list || list.length === 0) return "";

    if (format === "srt") {
      return list
        .map(function (c, i) {
          var body =
            state.targetLang === "both" &&
            c.subText &&
            c.subText !== c.text
              ? c.text + "\n" + c.subText
              : c.text;
          return (
            i +
            1 +
            "\n" +
            formatTime(c.start, true) +
            " --> " +
            formatTime(c.end, true) +
            "\n" +
            body +
            "\n"
          );
        })
        .join("\n");
    }

    var lines = ["WEBVTT", "NOTE Generated by VTT (@momalekiii)", ""];
    list.forEach(function (c) {
      var body =
        state.targetLang === "both" && c.subText && c.subText !== c.text
          ? c.text + "\n" + c.subText
          : c.text;
      lines.push(
        formatTime(c.start, false) + " --> " + formatTime(c.end, false)
      );
      lines.push(body);
      lines.push("");
    });
    return lines.join("\n");
  }

  function translateOnlineText(text, targetLang, cb) {
    var clean = (text || "").replace(/\s+/g, " ").trim();
    if (!clean) {
      cb({ main: "", sub: "" });
      return;
    }

    if (
      typeof chrome !== "undefined" &&
      chrome.runtime &&
      chrome.runtime.sendMessage
    ) {
      try {
        chrome.runtime.sendMessage(
          { type: "VTT_TRANSLATE", text: clean, targetLang: targetLang },
          function (res) {
            if (chrome.runtime.lastError || !res || !res.ok) {
              directTranslateFallback(clean, targetLang, cb);
              return;
            }
            if (targetLang === "both") {
              cb({ main: res.fa || clean, sub: res.en || clean });
            } else {
              cb({ main: res.text || clean, sub: "" });
            }
          }
        );
        return;
      } catch (_err) {}
    }

    directTranslateFallback(clean, targetLang, cb);
  }

  function directTranslateFallback(clean, targetLang, cb) {
    var lang = targetLang === "both" ? "fa" : targetLang || "fa";
    var url =
      "https://translate.googleapis.com/translate_a/single?client=gtx&sl=auto&tl=" +
      encodeURIComponent(lang) +
      "&dt=t&q=" +
      encodeURIComponent(clean);

    fetch(url)
      .then(function (r) {
        return r.json();
      })
      .then(function (data) {
        var tr = (data[0] || [])
          .map(function (x) {
            return Array.isArray(x) ? x[0] : "";
          })
          .join("")
          .trim();
        if (lang === "fa") tr = normalizeFa(tr);
        cb({
          main: tr || clean,
          sub: targetLang === "both" ? clean : "",
        });
      })
      .catch(function () {
        cb({ main: clean, sub: "" });
      });
  }

  /**
   * Pre-warm translation cache for the next 3 upcoming cues so transitions are instant
   */
  function prefetchUpcomingCues(startIndex) {
    if (!state.cues || state.cues.length === 0) return;
    for (
      var i = startIndex + 1;
      i <= Math.min(state.cues.length - 1, startIndex + 3);
      i++
    ) {
      var nextCue = state.cues[i];
      if (nextCue && nextCue.text && !nextCue.__prefetched) {
        nextCue.__prefetched = true;
        translateOnlineText(nextCue.text, state.targetLang, function () {});
      }
    }
  }

  function getMountContainer() {
    var fs =
      document.fullscreenElement || document.webkitFullscreenElement || null;
    if (fs && fs.tagName !== "VIDEO" && fs.appendChild) {
      return fs;
    }
    return document.body || document.documentElement;
  }

